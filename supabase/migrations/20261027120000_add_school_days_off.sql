create table public.school_days_off (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('vacation', 'day_off')),
  title text not null check (char_length(title) between 1 and 120),
  start_date date not null,
  end_date date not null,
  note text check (note is null or char_length(note) <= 500),
  author_name text,
  created_at timestamptz not null default now(),
  constraint school_days_off_valid_range check (end_date >= start_date),
  constraint school_days_off_single_day check (kind <> 'day_off' or end_date = start_date)
);

create index school_days_off_start_date_idx on public.school_days_off (start_date);

alter table public.school_days_off enable row level security;
grant select on public.school_days_off to anon, authenticated;
grant insert, delete on public.school_days_off to authenticated;
grant usage, select on sequence public.school_days_off_id_seq to authenticated;

create policy "Anyone can read school days off"
  on public.school_days_off for select
  to anon, authenticated
  using (true);

create policy "Admins can add school days off"
  on public.school_days_off for insert
  to authenticated
  with check (private.is_admin());

create policy "Admins can delete school days off"
  on public.school_days_off for delete
  to authenticated
  using (private.is_admin());

