create table public.subject_materials (
  id bigint generated by default as identity primary key,
  subject text not null check (subject in ('Română', 'Matematică', 'Geografie')),
  subtitle text not null check (char_length(subtitle) between 1 and 120),
  body text check (body is null or char_length(body) <= 4000),
  image_paths text[] not null default '{}'::text[],
  author_name text,
  created_at timestamptz not null default now(),
  constraint subject_materials_image_count check (cardinality(image_paths) <= 20)
);

create index subject_materials_subject_created_at_idx
  on public.subject_materials (subject, created_at desc);

alter table public.subject_materials enable row level security;
grant select on public.subject_materials to anon, authenticated;
grant insert, delete on public.subject_materials to authenticated;
grant usage, select on sequence public.subject_materials_id_seq to authenticated;

create policy "Anyone can read subject materials"
  on public.subject_materials for select
  to anon, authenticated
  using (true);

create policy "Admins can add subject materials"
  on public.subject_materials for insert
  to authenticated
  with check (private.is_admin());

create policy "Admins can delete subject materials"
  on public.subject_materials for delete
  to authenticated
  using (private.is_admin());

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'subject_materials'
     ) then
    execute 'alter publication supabase_realtime add table public.subject_materials';
  end if;
end;
$$;
