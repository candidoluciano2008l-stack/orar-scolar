create table public.subject_tests (
  id bigint generated by default as identity primary key,
  subject text not null check (char_length(subject) between 1 and 120),
  test_date date not null,
  title text check (title is null or char_length(title) <= 120),
  note text check (note is null or char_length(note) <= 500),
  author_name text,
  created_at timestamptz not null default now()
);

create index subject_tests_date_idx on public.subject_tests (test_date);

alter table public.subject_tests enable row level security;
grant select on public.subject_tests to anon, authenticated;
grant insert, delete on public.subject_tests to authenticated;
grant usage, select on sequence public.subject_tests_id_seq to authenticated;

create policy "Anyone can read subject tests"
  on public.subject_tests for select
  to anon, authenticated
  using (true);

create policy "Admins can add subject tests"
  on public.subject_tests for insert
  to authenticated
  with check (private.is_admin());

create policy "Admins can delete subject tests"
  on public.subject_tests for delete
  to authenticated
  using (private.is_admin());

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'subject_tests'
     ) then
    execute 'alter publication supabase_realtime add table public.subject_tests';
  end if;
end;
$$;
